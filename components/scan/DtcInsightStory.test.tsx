// @vitest-environment jsdom
import { describe, expect, it } from 'vitest';
import { renderToStaticMarkup } from 'react-dom/server';
import { fireEvent, render, screen } from '@testing-library/react';
import fixture from '../dev/scanlab/yananails-story.json';
import { DtcInsightStory, canShowStory, ShippingExample } from './DtcInsightStory';
import type { DtcCommercialEvidence } from '../../lib/scanTypes';
const data = { ...fixture.commercial, presentation: fixture.presentation } as DtcCommercialEvidence;
describe('source-backed story', () => {
  it('uses the approved standard for other stores without copying Yananails products or advice', () => {
    const tests = [{ title: 'Show the refill cost with the starter', observation: 'Your starter contains three refillable bottles.', test: 'Compare starter and refill costs beside the buying button.', measure: 'Completed orders and margin per order.', evidence: [{ kind: 'store', source_url: 'https://refill.com/products/starter', quote: 'three refillable bottles' }] }];
    const standard = { ...data, tests, presentation: { version: 'rise-standard-2026-10-14', domain: 'refill.com', headline: 'From first order to refill.', intro: 'We reviewed your public ads and store pages. Here are the changes worth discussing.', review: { approved: true, checked_at: '2026-10-14T00:00:00Z' }, sections: tests.map((t, i) => ({ test_index: i, headline: t.title, body: t.observation, action: t.test, lane: 'store' })) } } as any;
    expect(canShowStory(standard)).toBe(true);
    expect(canShowStory(standard, undefined, 'unrelated.com')).toBe(false);
    const moved = structuredClone(standard); moved.presentation.requested_domain = 'old-refill.com';
    expect(canShowStory(moved, undefined, 'old-refill.com')).toBe(true);
    const html = renderToStaticMarkup(<DtcInsightStory companyName="Refill Co" domain="refill.com" data={standard} ads={{ meta: { status: 'blocked' } }} bookingUrl="https://example.com/meeting" logo="https://example.com/logo.png" />);
    expect(html).toContain('Ready to grow Refill Co with paid ads?');
    expect(html).toContain('Public ad records');
    expect(html).not.toContain('all Yananails fiber-gel colours');
    expect(html).not.toContain('Add Primer + Bonder');
    expect(html).not.toContain('Free shipping above this amount in Sweden');
    expect(html).toContain('mattan-method-excerpt.mp4');
    const zero = renderToStaticMarkup(<DtcInsightStory companyName="Refill Co" domain="refill.com" data={standard} ads={{ meta: { status: 'empty', page_confirmed: true, data: { active_ad_count: 0 }, fetched_at: '2026-10-14T00:00:00Z', source_url: 'https://facebook.com/ads/library' }, google: { status: 'empty', data: { ads_found: 0 }, fetched_at: '2026-10-14T00:00:00Z', source_url: 'https://adstransparency.google.com/' } }} bookingUrl="https://example.com/meeting" logo="https://example.com/logo.png" />);
    expect(zero.match(/<strong>0<\/strong>/g)).toHaveLength(2);
    expect(zero).not.toContain('Ad activity could not be verified');
    const broken = structuredClone(standard); broken.presentation.sections[0].body = 'Unreviewed replacement claim';
    expect(canShowStory(broken)).toBe(false);
    expect(canShowStory({ ...standard, presentation: { ...standard.presentation, review: { approved: false } } })).toBe(false);
    expect(canShowStory({ ...standard, presentation: { ...standard.presentation, sections: [null] } })).toBe(false);
    const exact = structuredClone(standard); exact.tests[0].observation += ' Source wording – retained.'; exact.presentation.sections[0].body = exact.tests[0].observation;
    const exactHtml = renderToStaticMarkup(<DtcInsightStory companyName="Refill Co" domain="refill.com" data={exact} ads={{}} bookingUrl="https://example.com/meeting" logo="https://example.com/logo.png" />);
    expect(exactHtml).toContain('Source wording – retained.');
  });
  it('requires approved story version, complete evidence and the actual recorded ad destination', () => {
    expect(canShowStory(data, fixture.ads.meta)).toBe(true);
    expect(canShowStory({ ...data, status: 'error' }, fixture.ads.meta)).toBe(false);
    expect(canShowStory({ ...data, presentation: { ...data.presentation!, review: { approved: false, checked_at: '' } } }, fixture.ads.meta)).toBe(false);
    expect(canShowStory(data, { ...fixture.ads.meta, status: 'blocked' })).toBe(false);
    expect(canShowStory({ ...data, presentation: { ...data.presentation!, version: 'unknown' } }, fixture.ads.meta)).toBe(false);
    expect(canShowStory({ ...data, tests: [] }, fixture.ads.meta)).toBe(false);
    expect(canShowStory({ ...data, journeys: [] }, fixture.ads.meta)).toBe(false);
  });
  it('puts the paid insight before store suggestions, with dated activity and no performance claim', () => {
    const html = renderToStaticMarkup(<DtcInsightStory companyName="Yananails" domain="yananails.com" data={data} ads={fixture.ads} bookingUrl="https://example.com/meeting" logo="https://example.com/logo.png" />);
    expect(html.indexOf('id="paid-media"')).toBeLessThan(html.indexOf('id="product-pair"'));
    expect(html).toContain('3');
    expect(html).toContain('Checked 13 Oct 2026');
    expect(html).toContain('Checked 8 Oct 2026');
    expect(html).toContain('Public ad records do not show spend or sales.');
    expect(html).toContain('mattan.jpg');
    expect(html).toContain(fixture.ads.meta.source_url.replaceAll('&', '&amp;'));
    expect(html).toContain(fixture.ads.google.source_url.replaceAll('&', '&amp;'));
    const capped = renderToStaticMarkup(<DtcInsightStory companyName="Yananails" domain="yananails.com" data={data} ads={{ ...fixture.ads, google: { ...fixture.ads.google, data: { ...fixture.ads.google.data, capped: true } } }} bookingUrl="https://example.com/meeting" logo="https://example.com/logo.png" />);
    expect(capped).toContain('At least');
    expect(html).not.toContain('What we will test first');
    const blocked = renderToStaticMarkup(<DtcInsightStory companyName="Yananails" domain="yananails.com" data={data} ads={{ ...fixture.ads, google: { status: 'blocked', data: { ads_found: 900 } } }} bookingUrl="https://example.com/meeting" logo="https://example.com/logo.png" />);
    expect(blocked).not.toContain('<strong>900</strong>');
    expect(blocked).not.toContain('Google creatives');
  });
  it('takes the two primary findings into a RISE introduction and call, with extra ideas collapsed', () => {
    const html = renderToStaticMarkup(<DtcInsightStory companyName="Yananails" domain="yananails.com" data={data} ads={fixture.ads} bookingUrl="https://example.com/meeting" logo="https://example.com/logo.png" cases={[{ name: 'Josie Maran', url: 'https://risedtc.com/projects/josie-maran/', headline: '28% increase in revenue' }]} />);
    const doc = new DOMParser().parseFromString(html, 'text/html');
    const extras = doc.querySelector<HTMLDetailsElement>('#other-store-ideas')!;
    expect(extras.open).toBe(false);
    expect(doc.getElementById('buying-guidance')!.closest('details')).toBe(extras);
    expect(doc.getElementById('free-shipping')!.closest('details')).toBe(extras);
    expect(html.indexOf('id="product-pair"')).toBeLessThan(html.indexOf('id="rise-method"'));
    expect(html.indexOf('id="rise-method"')).toBeLessThan(html.indexOf('id="rise-conversation"'));
    expect(html.indexOf('id="rise-conversation"')).toBeLessThan(html.indexOf('id="other-store-ideas"'));
    expect(html).toContain('28% increase in revenue');
    const video = doc.querySelector('video')!;
    expect(video.getAttribute('preload')).toBe('none');
    expect(video.hasAttribute('autoplay')).toBe(false);
    expect(video.querySelector('source')!.getAttribute('src')).toContain('mattan-method-excerpt.mp4');
    expect(video.querySelector('track')!.getAttribute('kind')).toBe('captions');
    expect(video.closest('details')!.open).toBe(false);
    expect(html).toContain('Meta and Google campaigns');
    expect(html).toContain('Ready to grow Yananails with paid ads?');
    expect(doc.querySelector('.ris-booking')!.getAttribute('href')).toBe('https://example.com/meeting');
    expect(html).not.toMatch(/performance-only|no retainers|only get paid|guaranteed/i);
  });
  it('treats free shipping as strictly above the threshold and labels the basket as an example', () => {
    render(<ShippingExample data={data.presentation!.shipping} />);
    expect(screen.getByText('Example basket')).toBeTruthy();
    const input = screen.getByLabelText('Example basket value in SEK');
    fireEvent.change(input, { target: { value: '910' } });
    fireEvent.click(screen.getByRole('button', { name: /Add Nagellim/ }));
    expect(screen.getByText('999 SEK')).toBeTruthy();
    expect(screen.getByText('Free shipping starts above 999 SEK')).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: /Add MULTI-MIST/ }));
    expect(screen.getByText('1,118 SEK')).toBeTruthy();
    expect(screen.getByText('Above the free-shipping threshold')).toBeTruthy();
  });
});
